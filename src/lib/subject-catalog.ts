// Names only: course codes differ by batch and department, so the student types their own.

export interface CatalogSubject {
  name: string;
  programme: string;
  /** Short forms students search by, e.g. "DBMS". */
  aliases?: string[];
}

const group = (programme: string, items: (string | [string, ...string[]])[]): CatalogSubject[] =>
  items.map((i) => (typeof i === "string" ? { name: i, programme } : { name: i[0], programme, aliases: i.slice(1) }));

